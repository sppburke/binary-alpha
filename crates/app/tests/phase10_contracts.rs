#[test]
fn pinned_used_fields_types_nullability_enums_and_required_members() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("schemas/deriv/production_v20260819_0");
    let names = [
        "active_symbols",
        "balance",
        "buy",
        "contracts_for",
        "forget",
        "get_accounts",
        "portfolio",
        "proposal",
        "proposal_open_contract",
        "statement",
        "ticks",
        "ticks_history",
        "transaction",
        "websocket",
        "ws_public",
        "ws_demo",
        "ws_real",
    ];
    let mut schemas = std::collections::BTreeMap::new();
    for name in names {
        for direction in ["request", "response"] {
            let name = format!("{name}_{direction}");
            let bytes = std::fs::read(root.join(format!("{name}.schema.json"))).unwrap();
            let value: serde_json::Value = serde_json::from_slice(&bytes).unwrap();
            assert_eq!(value["type"], "object");
            schemas.insert(name, value);
        }
    }
    assert_eq!(schemas.len(), 34);
    for &(name, pointer, types, enums, required) in FIELDS {
        let schema = &schemas[name];
        let node = schema
            .pointer(pointer)
            .unwrap_or_else(|| panic!("missing {name}{pointer}"));
        assert_eq!(
            node["type"],
            serde_json::from_str::<serde_json::Value>(types).unwrap(),
            "{name}{pointer} type/nullability"
        );
        assert_eq!(
            node["enum"],
            serde_json::from_str::<serde_json::Value>(enums).unwrap(),
            "{name}{pointer} enum"
        );
        if !pointer.ends_with("/items") {
            let (parent, field) = pointer.rsplit_once("/properties/").unwrap();
            let parent = schema.pointer(parent).unwrap();
            let actual = parent["required"]
                .as_array()
                .is_some_and(|list| list.iter().any(|item| item == field));
            assert_eq!(actual, required, "{name}{pointer} required membership");
        }
    }
    let contract =
        &schemas["proposal_open_contract_response"]["properties"]["proposal_open_contract"];
    assert!(contract.get("required").is_none());
    assert!(
        schemas["ticks_history_request"]["properties"]["count"]
            .get("maximum")
            .is_none()
    );
}
